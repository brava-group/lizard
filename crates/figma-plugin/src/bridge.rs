//! Bounded document edits returned by the isolated Figma JavaScript worker.
//! The host validates and applies these through engine commands after JavaScript completes.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::time::{Duration, Instant};

use boa_engine::{Context, Source};

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "camelCase")]
pub enum Edit {
    CreateNode { id: String, node_type: String },
    SetNode { id: String, key: String, value: Value },
    AppendChild { parent: String, id: String, x: f64, y: f64 },
    Resize { id: String, width: f64, height: f64 },
    Rescale { id: String, factor: f64 },
    Select { ids: Vec<String> },
    Zoom { ids: Vec<String> },
    CreateCollection { id: String, name: String },
    RenameMode { collection: String, mode: String, name: String },
    CreateVariable { id: String, collection: String, name: String, kind: String },
    SetVariable { id: String, mode: String, value: Value },
    Notify { message: String },
}

/// The setup is a Rust string because native workers must not load code from outside their
/// authenticated request. Only JSON values generated by serde are interpolated.
pub fn setup(selection: &Value, extra: &Value, command: &Value, html: &Value, named_html: &Value, max_ops: usize, max_html: usize) -> String {
    let values = format!(
        "const __fcSelection = {selection}; const __fcExtra = {extra}; const __fcCommand = {command}; const __fcHtml = {html}; const __fcNamed = {named_html}; const __fcMaxOps = {max_ops}; const __fcMaxHtml = {max_html};\n"
    );
    values + API
}

/// Run short plugin timers inside the worker while respecting its outer two-second deadline.
/// This covers delayed UI replies without granting the plugin an unbounded background loop.
pub fn run_timers(context: &mut Context) -> Result<(), String> {
    let started = Instant::now();
    for _ in 0..32 {
        let value = context.eval(Source::from_bytes("__figcraftNextTimerDelay()")).map_err(|e| format!("plugin timer: {e}"))?;
        let delay = value.to_number(context).map_err(|e| format!("plugin timer: {e}"))?;
        if delay < 0.0 {
            return Ok(());
        }
        if !delay.is_finite() || delay > 1000.0 {
            return Err("plugin timer delay is invalid".into());
        }
        let remaining = Duration::from_millis(1500).saturating_sub(started.elapsed());
        let wait = Duration::from_millis(delay.ceil() as u64);
        if wait > remaining {
            return Err("plugin timers exceeded the 1.5-second limit".into());
        }
        if !wait.is_zero() {
            std::thread::sleep(wait);
        }
        context.eval(Source::from_bytes("__figcraftFireTimer()")).map_err(|e| format!("plugin timer: {e}"))?;
        context.run_jobs().map_err(|e| format!("plugin timer task: {e}"))?;
    }
    Err("plugin timer limit exceeded".into())
}

const API: &str = r#"
(() => {
    const edits = [];
    const messages = [];
    const opacityOps = [];
    const timers = [];
    const events = Object.create(null);
    let shown = null;
    let closed = false;
    let closeMessage = null;
    let eventResult = null;
    let nextId = 1;
    const add = edit => {
        if (closed) throw Error('plugin is closed');
        if (edits.length + opacityOps.length >= __fcMaxOps) throw Error('plugin operation limit exceeded');
        edits.push(edit);
    };
    const checkNumber = (value, name) => {
        if (typeof value !== 'number' || !Number.isFinite(value) || Math.abs(value) > 1000000)
            throw RangeError(name + ' must be a finite number');
        return value;
    };
    const tempId = () => 'plugin:' + nextId++;
    function wrapNode(data) {
        const state = { id: data.id, name: data.name ?? '', type: data.type ?? 'RECTANGLE',
            x: data.x ?? 0, y: data.y ?? 0, width: data.width ?? 100,
            height: data.height ?? 100, opacity: data.opacity ?? 1,
            fills: data.fills ?? [], strokes: data.strokes ?? [],
            strokeWeight: data.strokeWeight ?? 1, strokeAlign: data.strokeAlign ?? 'CENTER',
            constraints: data.constraints ?? { horizontal: 'MIN', vertical: 'MIN' },
            characters: data.characters ?? '', fontSize: data.fontSize ?? 12,
            textAlignHorizontal: data.textAlignHorizontal ?? 'LEFT',
            textAlignVertical: data.textAlignVertical ?? 'TOP' };
        const node = { id: state.id };
        for (const key of Object.keys(state)) {
            if (key === 'id') continue;
            Object.defineProperty(node, key, { enumerable: true,
                get() { return state[key]; },
                set(value) {
                    if (key === 'type') throw Error('node type is read-only');
                    if (['x','y','width','height','opacity','strokeWeight','fontSize'].includes(key))
                        checkNumber(value, key);
                    if (key === 'opacity' && (value < 0 || value > 1))
                        throw RangeError('opacity must be from 0 to 1');
                    state[key] = value;
                    if (key === 'opacity' && !state.id.startsWith('plugin:')) {
                        if (edits.length + opacityOps.length >= __fcMaxOps) throw Error('plugin operation limit exceeded');
                        opacityOps.push({ id: state.id, opacity: value });
                    } else add({ type: 'setNode', id: state.id, key, value });
                }
            });
        }
        node.resize = node.resizeWithoutConstraints = (width, height) => {
            state.width = checkNumber(width, 'width');
            state.height = checkNumber(height, 'height');
            add({ type: 'resize', id: state.id, width, height });
        };
        node.rescale = factor => {
            checkNumber(factor, 'factor');
            if (factor <= 0) throw RangeError('factor must be positive');
            state.width *= factor; state.height *= factor;
            add({ type: 'rescale', id: state.id, factor });
        };
        node.appendChild = child => {
            if (!child || typeof child.id !== 'string') throw TypeError('child must be a node');
            add({ type: 'appendChild', parent: state.id, id: child.id, x: child.x, y: child.y });
        };
        return node;
    }
    const selected = (__fcSelection ?? []).map(wrapNode);
    const page = {
        get selection() { return selected.slice(); },
        set selection(nodes) {
            if (!Array.isArray(nodes) || nodes.some(node => !node || typeof node.id !== 'string'))
                throw TypeError('selection must be an array of nodes');
            selected.splice(0, selected.length, ...nodes);
            add({ type: 'select', ids: nodes.map(node => node.id) });
        },
        appendChild(node) {
            if (!node || typeof node.id !== 'string') throw TypeError('child must be a node');
            add({ type: 'appendChild', parent: 'page', id: node.id, x: node.x, y: node.y });
        }
    };
    function createNode(type) {
        const id = tempId();
        add({ type: 'createNode', id, node_type: type });
        return wrapNode({ id, type });
    }
    const ui = {
        onmessage: null,
        postMessage(value) {
            if (messages.length >= 128) throw Error('plugin message limit exceeded');
            messages.push(value);
        },
        resize(width, height) {
            if (!shown) throw Error('plugin UI is not open');
            figma.showUI(shown.html, { width, height, title: shown.title });
        },
        close() { closed = true; }
    };
    const variables = {
        createVariableCollection(name) {
            const id = tempId();
            add({ type: 'createCollection', id, name: String(name) });
            const modeId = id + '/mode1';
            return { id, name: String(name), modes: [{ modeId, name: 'Mode 1' }],
                renameMode(mode, name) {
                    add({ type: 'renameMode', collection: id, mode: String(mode), name: String(name) });
                    if (mode === modeId) this.modes[0].name = String(name);
                } };
        },
        createVariable(name, collection, kind) {
            if (!collection || typeof collection.id !== 'string') throw TypeError('invalid variable collection');
            const id = tempId();
            add({ type: 'createVariable', id, collection: collection.id,
                name: String(name), kind: String(kind) });
            return { id, name: String(name), resolvedType: String(kind),
                setValueForMode(mode, value) {
                    add({ type: 'setVariable', id, mode: String(mode), value });
                } };
        }
    };
    const figma = Object.freeze({
        editorType: 'figma',
        command: __fcCommand ?? '',
        currentPage: page,
        viewport: Object.freeze({
            center: Object.freeze(__fcExtra?.center ?? { x: 0, y: 0 }),
            scrollAndZoomIntoView(nodes) {
                if (!Array.isArray(nodes)) throw TypeError('nodes must be an array');
                add({ type: 'zoom', ids: nodes.map(node => node.id) });
            }
        }),
        parameters: Object.freeze({ on(name, callback) {
            if (name !== 'input' || typeof callback !== 'function') throw TypeError('unsupported parameter event');
            events.parametersInput = callback;
        } }),
        variables,
        ui,
        createRectangle() { return createNode('rectangle'); },
        createFrame() { return createNode('frame'); },
        createText() { return createNode('text'); },
        getLocalPaintStylesAsync() { return Promise.resolve(__fcExtra?.styles ?? []); },
        loadFontAsync(font) {
            if (!font || typeof font.family !== 'string') return Promise.reject(Error('invalid font'));
            return Promise.resolve();
        },
        on(name, callback) {
            if (typeof callback !== 'function') throw TypeError('event callback must be a function');
            events[name] = callback;
        },
        notify(value) {
            add({ type: 'notify', message: String(value).slice(0, 4096) });
        },
        showUI(value, options = {}) {
            if (typeof value !== 'string' || value.length > __fcMaxHtml) throw Error('invalid plugin HTML');
            const width = options.width === undefined ? 300 : options.width;
            const height = options.height === undefined ? 200 : options.height;
            if (!Number.isInteger(width) || width < 100 || width > 1200 ||
                !Number.isInteger(height) || height < 100 || height > 1000)
                throw RangeError('plugin UI size is out of range');
            shown = { html: value, width, height,
                title: options.title == null ? null : String(options.title).slice(0, 128) };
        },
        closePlugin(value) {
            closed = true;
            closeMessage = value === undefined ? null : String(value).slice(0, 4096);
        }
    });
    Object.defineProperty(globalThis, 'figma', { value: figma, writable: false });
    Object.defineProperty(globalThis, '__html__', { value: __fcHtml, writable: false });
    Object.defineProperty(globalThis, '__uiFiles__', { value: Object.freeze(__fcNamed ?? {}), writable: false });
    Object.defineProperty(globalThis, 'console', { value: Object.freeze({
        log() {}, info() {}, warn() {}, error() {}, clear() {}
    }), writable: false });
    Object.defineProperty(globalThis, 'setTimeout', { value: (callback, delay = 0) => {
        if (typeof callback !== 'function') throw TypeError('timer callback must be a function');
        if (timers.length >= 32) throw Error('plugin timer limit exceeded');
        timers.push({ callback, at: Date.now() + Math.min(1000, Math.max(0, Number(delay) || 0)) });
        timers.sort((a, b) => a.at - b.at);
        return timers.length;
    }, writable: false });
    Object.defineProperty(globalThis, '__figcraftNextTimerDelay', { value: () =>
        timers.length ? Math.max(0, timers[0].at - Date.now()) : -1 });
    Object.defineProperty(globalThis, '__figcraftFireTimer', { value: () => {
        const timer = timers.shift();
        if (timer) timer.callback();
    } });
    Object.defineProperty(globalThis, '__figcraftRun', { value: () => {
        if (__fcExtra?.parameterInput && typeof events.parametersInput === 'function') {
            const input = __fcExtra.parameterInput;
            eventResult = { suggestions: [], error: null };
            events.parametersInput({ query: String(input.query ?? ''), key: String(input.key ?? ''),
                result: {
                    setSuggestions(items) {
                        if (!Array.isArray(items)) throw TypeError('suggestions must be an array');
                        eventResult.suggestions = items.slice(0, 16).map(item => String(item).slice(0, 128));
                    },
                    setError(message) { eventResult.error = String(message).slice(0, 256); }
                } });
        } else if (__fcCommand === 'textreview' && typeof events.textreview === 'function')
            eventResult = events.textreview({ text: String(__fcExtra?.text ?? '') });
        else if (typeof events.run === 'function')
            events.run({ command: __fcCommand ?? '', parameters: __fcExtra?.parameters ?? null });
    } });
    Object.defineProperty(globalThis, '__figcraftReceive', { value: payload => {
        if (closed) throw Error('plugin is closed');
        if (typeof ui.onmessage === 'function') ui.onmessage(payload);
    } });
    Object.defineProperty(globalThis, '__figcraftTake', { value: () => {
        const result = JSON.stringify({ operations: opacityOps, edits, show: shown,
            messages, closed, message: closeMessage, eventResult });
        shown = null;
        messages.length = 0;
        opacityOps.length = 0;
        edits.length = 0;
        eventResult = null;
        return result;
    } });
})();
"#;
