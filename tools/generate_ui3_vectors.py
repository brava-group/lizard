rows = []
for line in mapping.strip().splitlines():
    variant, name = line.split()
    if name not in by_name:
        raise RuntimeError(f"UI3 icon {name} missing (for {variant})")
    rows.append(f"        super::super::Icon::{variant} => Some({by_name[name]}),")
