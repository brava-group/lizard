"""Regenerate vector UI3 SVG data and the FigCraft icon map from 3icons."""

import json
from pathlib import Path
import re
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
PAGE = "https://3icons.pages.dev/"
request = urllib.request.Request(PAGE, headers={"User-Agent": "Mozilla/5.0"})
html = urllib.request.urlopen(request).read().decode()
bundle = re.search(r'src="(/assets/index-[^"]+\.js)"', html)
if bundle is None:
    raise RuntimeError("3icons bundle not found")
request = urllib.request.Request(PAGE.rstrip("/") + bundle.group(1), headers={"User-Agent": "Mozilla/5.0"})
js = urllib.request.urlopen(request).read().decode()
svg_by_var = dict(re.findall(r"([\w$]+)='(<svg.*?</svg>)'", js))
entries = re.findall(r'"\.\./node_modules/@ui3/icons/dist/([^\"]+\.svg)":([\w$]+)', js)
if len(entries) < 300:
    raise RuntimeError(f"expected the full UI3 catalog, got {len(entries)} icons")

names = []
vectors = []
for filename, variable in entries:
    svg = svg_by_var.get(variable)
    if svg is None:
        raise RuntimeError(f"SVG missing for {filename}")
    name = re.sub(r"-[A-Z0-9]{8}\.svg$", "", filename)
    names.append(name)
    vectors.append(svg)

out = ROOT / "crates/ui-egui/assets/ui3-vectors.json"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(vectors, separators=(",", ":")))

